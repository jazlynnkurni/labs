"""Build the Eden CPT deck on the Clover case-study engine.
python3 build.py  ->  deck.html (and STRUCTURE.md, titles plus speaker notes).

Every word on the slides lives in slides.py. The engine (deck.js, lens.html, sheets-gl.js), base.css and
clover.css are copied from ~/Desktop/clover-doordash-deck/deck; eden.css holds the few additions this deck needs."""
import re, html, pathlib

HERE = pathlib.Path(__file__).parent
CHAPTERS = []
FOOT_T = ''

def chapter_of(n):
    cur = None
    for name, start in CHAPTERS:
        if n >= start: cur = name
    return cur

def foot(n):
    ch = chapter_of(n)
    links = ''.join(f'<a class="{"on" if name == ch else ""}" data-go="{start}">{name}</a>' for name, start in CHAPTERS)
    return f'<div class="foot"><span class="n">{n:02d}</span><span class="ch">{links}</span><span class="t">{FOOT_T}</span></div>'

def slide(n, title, body, fn='', cover=False, notes=''):
    head = '' if cover else f'<div class="head"><div><h2>{title}</h2></div></div>'
    fnh = f'<p class="fn">{fn}</p>' if fn else ''
    nh = f'<aside class="notes" hidden>{notes}</aside>' if notes else ''
    return (f'<section class="s"><img class="sigtr" src="img/jaz-signature.svg" alt="Jazlynn"><div class="wrap">{head}{body}{fnh}</div>{foot(n)}{nh}</section>')

def hl(a, b): return f'{a} <em class="hl">{b}</em>'

exec((HERE / 'slides.py').read_text(encoding='utf-8'))

SCRIPT = (HERE / 'deck.js').read_text(encoding='utf-8')
css = '\n'.join((HERE / f).read_text(encoding='utf-8') for f in ('base.css', 'clover.css', 'eden.css'))
HEAD = '<title>CPT at Eden</title>\n<link rel="icon" href="data:,">\n<meta name="viewport" content="width=device-width,initial-scale=1">\n<style>' + css + '</style>'
LENS = (HERE / 'lens.html').read_text(encoding='utf-8')
# the opening slides load first: images from the third slide on are asked for at low priority (as in Clover)
S = [x if k < 2 else x.replace('<img ', '<img fetchpriority="low" decoding="async" ') for k, x in enumerate(S)]
BODY = (LENS + '<div id="stage"><div id="slide">\n' + '\n'.join(S) + '\n</div></div>\n'
        '<button class="arrow l" id="prev" aria-label="Previous slide"><svg viewBox="0 0 24 24"><path d="M15 6l-6 6 6 6"/></svg></button>\n'
        '<button class="arrow r" id="next" aria-label="Next slide"><svg viewBox="0 0 24 24"><path d="M9 6l6 6-6 6"/></svg></button>\n'
        '<div id="bar"><i></i></div>\n<script>' + SCRIPT + '</script>')
# the vellum disc from jazlynnwashere.com, inlined as a module exactly as the Clover build does
DISC = (HERE / 'sheets-gl.js').read_text(encoding='utf-8').replace('export function mountSheets', 'function mountSheets')
BODY = BODY.replace('<script>', '<script>window.DISCS=' + (HERE / 'discs.json').read_text(encoding='utf-8') + ';\n', 1)
BODY += '\n<script type="module">' + DISC + '\nwindow.mountSheets = mountSheets;</script>'
# the intro deck's living print (riso-gl.js): photos in .ph2 print in one plum ink as a moving ordered dither
BODY += '\n<script type="module">import {mountPrint} from "./riso-gl.js"; document.querySelectorAll(".ph2").forEach(el=>mountPrint(el,{src:el.dataset.src,ink:[52,4,20],w:+el.dataset.w,h:+el.dataset.h,fit:"cover"}).catch(()=>{}));</script>'
(HERE / 'deck.html').write_text('<!doctype html>\n<html lang="en">\n<meta charset="utf-8">\n' + HEAD + '\n' + BODY, encoding='utf-8')

def plain(x): return html.unescape(re.sub(r'<[^>]+>', '', x)).strip()
out = ['# Eden CPT deck structure', '', 'Generated by build.py from slides.py. Edit slides.py, then run `python3 build.py`.', '']
for k, s in enumerate(S):
    t = re.search(r'<h[12]>(.*?)</h[12]>', s, re.S)
    nt = re.search(r'<aside class="notes" hidden>(.*?)</aside>', s, re.S)
    out += [f'{k+1}. [{chapter_of(k+1) or "Opening"}] {plain(t.group(1)) if t else ""}', f'   Notes: {plain(nt.group(1)) if nt else ""}', '']
(HERE / 'STRUCTURE.md').write_text('\n'.join(out), encoding='utf-8')
print('built', len(S), 'slides')
